import WebSocket from 'ws';
import { writeFileSync, readFileSync } from 'node:fs';
const req = JSON.parse(readFileSync('/tmp/shotreq.json', 'utf8'));
const base = 'http://127.0.0.1:' + (process.env.SHOTPORT || '9333');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let id = 0; const pending = new Map();
const cmd = (ws, method, params = {}) => { const mid = ++id; return new Promise((res, rej) => { pending.set(mid, { res, rej }); ws.send(JSON.stringify({ id: mid, method, params })); }); };
const list = await (await fetch(base + '/json/list')).json();
const page = list.find((t) => t.type === 'page');
const ws = new WebSocket(page.webSocketDebuggerUrl, { maxPayload: 256 * 1024 * 1024 });
ws.on('message', (d) => { const m = JSON.parse(d.toString()); if (m.id && pending.has(m.id)) { const p = pending.get(m.id); pending.delete(m.id); m.error ? p.rej(new Error(JSON.stringify(m.error))) : p.res(m.result); } });
await new Promise((r) => ws.on('open', r));
await cmd(ws, 'Page.enable');
await cmd(ws, 'Emulation.setDeviceMetricsOverride', { width: req.width, height: req.height, deviceScaleFactor: req.dsf || 1, mobile: !!req.mobile });
await cmd(ws, 'Page.navigate', { url: req.url });
await sleep(req.wait || 7000);
const r = await cmd(ws, 'Page.captureScreenshot', { format: 'png', captureBeyondViewport: true });
writeFileSync(req.out, Buffer.from(r.data, 'base64'));
console.log('saved', req.out); ws.close(); process.exit(0);
